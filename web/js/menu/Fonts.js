import { createVault } from '../SecureAssets.js';
import * as FONT_KEY from '../fontKey.js';
import { FONT_PLAN } from '../fontPlan.js';
import { lang } from '../i18n.js';

// The menu's two fonts, never served as font files: tools/pack_fonts.mjs
// encrypts them into fonts/packed/, decrypted here in memory and added to the
// page as FontFaces (no @font-face url to download from the network tab).
//   brand — the titles (home walls, garage car names, Brand): one weight
//   text  — everything else: Figtree (SIL OFL 1.1, fonts/OFL-figtree.txt),
//           variable weight 300-900, upright (text) and italic (text-italic)
// A language whose letters a font lacks gets its substitute for that role
// (FONT_PLAN, generated by the packer), under the same family name (upright
// and italic alike: the substitutes have no italic).

const vault = createVault( 'fonts/packed/', '.bin', FONT_KEY );
const files = FONT_PLAN[ lang ] || {};

const FACES = [
	{ family: 'brand', file: 'brand', descriptors: {} },
	{ family: 'text', file: 'text', descriptors: { weight: '300 900' } },
	{ family: 'text', file: 'text-italic', descriptors: { weight: '300 900', style: 'italic' } },
];

// Resolves once both are usable (never rejects: the system fonts stand in)
export const fontsReady = Promise.all( FACES.map( async ( { family, file, descriptors } ) => {

	const face = new FontFace( family, await vault.load( files[ family ] || file ), descriptors );
	document.fonts.add( await face.load() );

} ) ).catch( ( e ) => console.warn( 'Fonts:', e ) );
